#!/usr/bin/env python3
"""Bundle only captured source pages; never bundle player responses or execute saved HTML."""
import argparse
import base64
import gzip
import html
import re
from pathlib import Path
from urllib.parse import urlsplit, parse_qsl

ROOT = Path(__file__).resolve().parents[1]
SITES = {
    'TwentyFourHD': [('regression/24hd.today', 'www.24hd.today')],
    'AHDZero': [('regression/ahdzero.com', 'ahdzero.com')],
    'ThaiAnime': [('nekomiku.net', 'nekomiku.net'), ('animeruka.com', 'animeruka.com'), ('suba-anime.com', 'suba-anime.com')],
}

def original(text):
    saved = re.search(r'saved from url=\(\d+\)(.*?) -->', text)
    if saved:
        return html.unescape(saved[1].strip())
    canonical = re.search(r'<link\b[^>]*rel=["\']canonical["\'][^>]*href=["\']([^"\']+)', text, re.I)
    if canonical:
        return html.unescape(canonical[1])
    raise ValueError('Missing recorded URL')

def clean(text, path):
    # Restore iframe URLs only from the browser's recorded child URL, never from a filename.
    def frame(match):
        tag = match[0]
        src = re.search(r'(?<!\S)src\s*=\s*(["\'])(.*?)\1', tag, re.I)
        if not src or '_files/' not in src[2]:
            return tag
        def replace_src(value):
            return tag[:src.start()] + value + tag[src.end():]
        child = (path.parent / html.unescape(src[2])).resolve()
        if not child.is_relative_to((ROOT / 'samples').resolve()) or not child.is_file():
            return replace_src('')
        try:
            url = original(child.read_text())
            if urlsplit(url).scheme != 'https' or any(k.lower() in ('token', 'ctx', 'sig', 't') for k, _ in parse_qsl(urlsplit(url).query)):
                return replace_src('')
            return replace_src('src="' + html.escape(url, quote=True) + '"')
        except (ValueError, UnicodeError):
            return replace_src('')
    text = re.sub(r'<iframe\b[^>]*>', frame, text, flags=re.I)
    # Catalog parsers consume DOM only. Saved script/session/token state is not a playback source.
    text = re.sub(r'<script\b[^>]*>[\s\S]*?</script\s*>', lambda m: m[0] if re.search(r'type=[\"\']application/ld\+json[\"\']', m[0].split('>')[0], re.I) else '', text, flags=re.I)
    text = re.sub(r'<!--.*?-->', '', text, flags=re.S)
    return text

def generate():
    results = {}
    for module, sites in SITES.items():
        entries = []
        for directory, host in sites:
            for path in sorted((ROOT / 'samples' / directory).glob('*.html')):
                kind = next((k for k in ('home', 'category', 'catagory', 'tag', 'series', 'movie', 'episode') if path.name.startswith(k)), None)
                if not kind:
                    continue
                text = path.read_text()
                url = original(text)
                parsed = urlsplit(url)
                if parsed.scheme != 'https' or parsed.hostname.removeprefix('www.') != host.removeprefix('www.') or any(k not in ("page", "paged") for k, _ in parse_qsl(parsed.query)) or parsed.fragment:
                    raise ValueError(f'Unexpected source URL in {path.relative_to(ROOT)}')
                kind = 'listing' if kind in ('home', 'category', 'catagory', 'tag') else 'episode' if kind == 'episode' else 'detail'
                packed = bytearray(gzip.compress(clean(text, path).encode(), compresslevel=9, mtime=0))
                # Python 3.11/3.12 may emit the zlib OS byte, while 3.13+ emits 255.
                # Normalize it so CI and local generation have identical headers.
                packed[9] = 255
                encoded = base64.b64encode(packed).decode()
                chunks = ',\n                '.join('"' + encoded[i:i+8000] + '"' for i in range(0, len(encoded), 8000))
                entries.append(f'        // {path.relative_to(ROOT)}\n        SamplePage("{url}", "{kind}", listOf(\n                {chunks}\n        ).joinToString("")),')
        output = '''// Generated by scripts/generate_sample_catalog.py. Do not edit manually.
package com.providers.samples

import com.providers.network.SampleArchive
import com.providers.network.SamplePage

internal val bundledSamples by lazy {
    SampleArchive(listOf(
%s
    ))
}
''' % '\n'.join(entries)
        target = ROOT / module / 'src/main/kotlin/com/providers/samples/BundledSamples.kt'
        results[target] = output
    return results

if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for target, content in generate().items():
        if args.check:
            if not target.exists() or target.read_text() != content:
                raise SystemExit(f'Stale generated catalog: {target.relative_to(ROOT)}')
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content)
        print(target.relative_to(ROOT))
